export function isValidCourseId(courseId) {
  if (!courseId || typeof courseId !== "string") return false;
  return PREPSPACES_COURSES.some((c) => c.id === courseId.trim().toLowerCase());
}

/**
 * Normalizes any module input identifier within a course context.
 * Preserves legacy AI Engineering aliases (M01-M24 / module-1 / slugs) while resolving real slugs across all courses.
 */
export function normalizeModuleId(moduleId, courseId = "ai-engineering") {
  if (!moduleId || String(moduleId).trim().toLowerCase() === "all") return "all";
  const raw = String(moduleId).trim();
  const upper = raw.toUpperCase();
  const course = PREPSPACES_COURSES.find((c) => c.id === courseId);

  if (course && course.id !== "ai-engineering") {
    const lower = raw.toLowerCase();
    const direct = course.modules.find(
      (m) => m.id.toLowerCase() === lower || (m.slug && m.slug.toLowerCase() === lower)
    );
    if (direct) return direct.id;
    const modNumMatch = raw.match(/^(?:M|MODULE[-_]?)?0?(d+)$/i);
    if (modNumMatch) {
      const idx = parseInt(modNumMatch[1], 10);
      if (idx >= 1 && idx < course.modules.length) {
        return course.modules[idx].id;
      }
    }
    return raw;
  }

  if (/^M\d{2}$/.test(upper)) return upper;
  if (/^M\d{1}$/.test(upper)) return `M0${upper.slice(1)}`;
  const modMatch = upper.match(/MODULE[-_]?(\d+)/i) || upper.match(/^(\d+)$/);
  if (modMatch) {
    const num = parseInt(modMatch[1], 10);
    if (num >= 1 && num <= 24) {
      return `M${String(num).padStart(2, "0")}`;
    }
  }
  return AI_SLUG_MAP[upper] || raw;
}

export function isValidModuleId(courseId, moduleId) {
  const course = PREPSPACES_COURSES.find((c) => c.id === courseId);
  if (!course) return false;
  if (!moduleId || String(moduleId).trim().toLowerCase() === "all") return true;
  const norm = normalizeModuleId(moduleId, courseId);
  return course.modules.some(
    (m) => m.id.toLowerCase() === String(norm).toLowerCase() || (m.slug && m.slug.toLowerCase() === String(norm).toLowerCase())
  );
}

/**
 * Returns course by ID with safe fallback
 */
export function getCourseById(courseId) {
  return PREPSPACES_COURSES.find((c) => c.id === courseId) || PREPSPACES_COURSES[0];
}

/**
 * Returns module by course ID and module ID with intelligent normalization
 */
export function getModuleById(courseId, moduleId) {
  const course = getCourseById(courseId);
  if (!course || !course.modules || course.modules.length === 0) return null;
  const targetId = moduleId || "all";
  const normalized = normalizeModuleId(targetId, course.id);

  let found = course.modules.find(
    (m) => m.id === targetId || m.id === normalized || (m.slug && (m.slug === targetId || m.slug === normalized))
  );
  if (found) return found;

  found = course.modules.find(
    (m) =>
      m.id.toLowerCase() === String(targetId).toLowerCase() ||
      m.id.toLowerCase() === String(normalized).toLowerCase()
  );
  if (found) return found;

  return course.modules[0];
}
